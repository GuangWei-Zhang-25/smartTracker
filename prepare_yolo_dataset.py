"""
YOLO Dataset Preparation
========================
Prepares single-target annotations for YOLO segmentation training.
Splits data into train/val sets and creates dataset.yaml.
"""

import cv2
import numpy as np
from pathlib import Path
import shutil
import argparse
import json
import random
from typing import List, Tuple


def prepare_dataset(images_dir: str, labels_dir: str, output_dir: str,
                   val_split: float = 0.2, class_name: str = "mouse",
                   seed: int = 42) -> str:
    """
    Prepare YOLO dataset from single-target labels.

    Args:
        images_dir: Directory containing source images
        labels_dir: Directory containing filtered single-target labels
        output_dir: Output directory for YOLO dataset
        val_split: Fraction for validation (default 0.2)
        class_name: Class name for the target
        seed: Random seed for reproducibility

    Returns:
        Path to dataset.yaml
    """
    images_dir = Path(images_dir)
    labels_dir = Path(labels_dir)
    output_dir = Path(output_dir)

    random.seed(seed)

    # Find all label files
    label_files = list(labels_dir.glob("*.txt"))
    label_files = [f for f in label_files if f.name != "selection_metadata.json"]

    print(f"Found {len(label_files)} label files")

    # Find matching images
    image_extensions = {'.jpg', '.jpeg', '.png', '.bmp'}
    pairs = []

    for label_path in label_files:
        stem = label_path.stem

        # Search for matching image
        img_path = None
        for ext in image_extensions:
            candidate = images_dir / f"{stem}{ext}"
            if candidate.exists():
                img_path = candidate
                break
            # Also check subdirectories
            for subdir in images_dir.iterdir():
                if subdir.is_dir():
                    candidate = subdir / f"{stem}{ext}"
                    if candidate.exists():
                        img_path = candidate
                        break

        if img_path:
            pairs.append((img_path, label_path))

    print(f"Found {len(pairs)} image-label pairs")

    if not pairs:
        print("No pairs found!")
        return None

    # Shuffle and split
    random.shuffle(pairs)
    n_val = int(len(pairs) * val_split)
    val_pairs = pairs[:n_val]
    train_pairs = pairs[n_val:]

    print(f"Train: {len(train_pairs)}, Val: {len(val_pairs)}")

    # Create directory structure
    train_images = output_dir / "images" / "train"
    train_labels = output_dir / "labels" / "train"
    val_images = output_dir / "images" / "val"
    val_labels = output_dir / "labels" / "val"

    for d in [train_images, train_labels, val_images, val_labels]:
        d.mkdir(parents=True, exist_ok=True)

    # Copy files
    def copy_pair(img_path, label_path, img_dst, label_dst):
        # Copy image
        shutil.copy2(img_path, img_dst / img_path.name)
        # Copy label
        shutil.copy2(label_path, label_dst / label_path.name)

    print("Copying training files...")
    for img_path, label_path in train_pairs:
        copy_pair(img_path, label_path, train_images, train_labels)

    print("Copying validation files...")
    for img_path, label_path in val_pairs:
        copy_pair(img_path, label_path, val_images, val_labels)

    # Create dataset.yaml
    yaml_content = f"""# YOLO Segmentation Dataset
# Generated by SmartTracker

path: {output_dir.absolute()}
train: images/train
val: images/val

# Class names
names:
  0: {class_name}

# Dataset statistics
nc: 1
"""

    yaml_path = output_dir / "dataset.yaml"
    with open(yaml_path, 'w') as f:
        f.write(yaml_content)

    # Save metadata
    meta = {
        'total_samples': len(pairs),
        'train_samples': len(train_pairs),
        'val_samples': len(val_pairs),
        'val_split': val_split,
        'class_name': class_name,
        'seed': seed,
    }

    with open(output_dir / "dataset_meta.json", 'w') as f:
        json.dump(meta, f, indent=2)

    print(f"\nDataset created at: {output_dir}")
    print(f"dataset.yaml: {yaml_path}")

    return str(yaml_path)


def main():
    parser = argparse.ArgumentParser(
        description="Prepare YOLO segmentation dataset from single-target labels"
    )
    parser.add_argument("images_dir", help="Directory containing images")
    parser.add_argument("labels_dir", help="Directory containing single-target labels")
    parser.add_argument("-o", "--output", required=True, help="Output dataset directory")
    parser.add_argument("--val-split", type=float, default=0.2,
                       help="Validation split ratio (default: 0.2)")
    parser.add_argument("--class-name", default="mouse",
                       help="Class name (default: mouse)")
    parser.add_argument("--seed", type=int, default=42,
                       help="Random seed (default: 42)")

    args = parser.parse_args()

    prepare_dataset(
        args.images_dir,
        args.labels_dir,
        args.output,
        val_split=args.val_split,
        class_name=args.class_name,
        seed=args.seed
    )


if __name__ == "__main__":
    main()
